export function detectLanguage() {
  try {
    const lang = (globalThis.navigator?.language || '').toLowerCase();
    return lang.startsWith('zh') ? 'zh' : 'en';
  } catch {
    return 'en';
  }
}

export function getStrings(lang) {
  return STRINGS[lang === 'zh' ? 'zh' : 'en'];
}
